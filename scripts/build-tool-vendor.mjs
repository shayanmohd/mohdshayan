// Copies the third-party code the free tools use from node_modules into /assets/tools/vendor/,
// so the site keeps serving everything itself (no CDN). Run after changing either dependency.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const OUT = 'assets/tools/vendor';
mkdirSync(OUT, { recursive: true });

// QR encoder: qrcode-generator by Kazuhiko Arase (MIT). The ES module build ships with its licence header intact.
const qr = readFileSync('node_modules/qrcode-generator/dist/qrcode.mjs', 'utf8');
const qrVersion = JSON.parse(readFileSync('node_modules/qrcode-generator/package.json', 'utf8')).version;
writeFileSync(`${OUT}/qrcode.js`, `// qrcode-generator ${qrVersion} (MIT), vendored by scripts/build-tool-vendor.mjs\n${qr}`);

// EFF Long Wordlist (7,776 words) for passphrases. © Electronic Frontier Foundation, CC BY 3.0 US: https://www.eff.org/dice
const words = JSON.parse(readFileSync('node_modules/@wordlist/english-eff/dist/data/long.json', 'utf8'));
if (words.length !== 7776 || new Set(words).size !== 7776) throw new Error(`unexpected EFF long list: ${words.length} words`);
writeFileSync(`${OUT}/eff-long-wordlist.js`, `// EFF Long Wordlist, 7,776 words. © Electronic Frontier Foundation, licensed CC BY 3.0 US (https://www.eff.org/dice).\n// Generated by scripts/build-tool-vendor.mjs from @wordlist/english-eff.\nexport default ${JSON.stringify(words.join(' '))}.split(' ');\n`);
console.log(`${OUT}: qrcode.js (${qrVersion}), eff-long-wordlist.js (${words.length} words)`);
